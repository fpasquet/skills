#!/usr/bin/env node
/**
 * Range les dossiers produits par les skills (disposition 1.x / 2.x, côte à côte à la racine du projet)
 * dans un seul dossier specs/, prêt à vivre dans le dépôt de code de l'application.
 *
 * Usage : node migrate-layout.mjs [project-dir] [--dry-run]
 *
 *   specs-ui/               → specs/ui/
 *   prototype-ui/           → specs/prototype/          src/prototype.json → specs : "../ui"
 *   cdc/                    → specs/requirements/       cdc.json → requirements.json, CDC.md → REQUIREMENTS.md,
 *                                                       <produit>-cahier-des-charges.* → requirements.*,
 *                                                       artifacts.cdc → artifacts.requirements
 *   design-system-package/  → specs/design-system-package/   package.json → specsUi : "../ui"
 *
 * Les URL d'artifacts, les fichiers .published.json et les mémoires sont conservés : les mises à jour
 * continuent d'aller vers les mêmes artifacts. Les sorties régénérables (cdc/publish/, .check/) ne sont pas
 * déplacées. Les chemins cités dans les mémoires (CONTEXTE.md…) restent à relire à la main.
 */
import { existsSync, readFileSync, writeFileSync, renameSync, mkdirSync, rmSync } from 'node:fs';
import { join, resolve } from 'node:path';

const args = process.argv.slice(2);
const project = resolve(args.find((a) => !a.startsWith('--')) ?? '.');
const dryRun = args.includes('--dry-run');
const target = join(project, 'specs');
const moves = [
  ['specs-ui', 'ui'],
  ['prototype-ui', 'prototype'],
  ['cdc', 'requirements'],
  ['design-system-package', 'design-system-package'],
].filter(([from]) => existsSync(join(project, from)));
if (!moves.length) {
  console.error(`Nothing to migrate in ${project} (no specs-ui/, prototype-ui/ or cdc/).`);
  process.exit(2);
}
for (const [, to] of moves) {
  if (existsSync(join(target, to))) {
    console.error(`specs/${to} already exists: migration stopped, nothing was moved.`);
    process.exit(1);
  }
}
const log = (msg) => console.log(`${dryRun ? '[dry-run] ' : ''}${msg}`);
const editJson = (path, edit) => {
  if (!existsSync(path)) return;
  const data = JSON.parse(readFileSync(path, 'utf8'));
  edit(data);
  if (!dryRun) writeFileSync(path, JSON.stringify(data, null, 2) + '\n');
  log(`updated ${path.slice(project.length + 1)}`);
};
const move = (from, to) => {
  if (!existsSync(from)) return;
  log(`${from.slice(project.length + 1)} → ${to.slice(project.length + 1)}`);
  if (!dryRun) renameSync(from, to);
};

if (!dryRun) mkdirSync(target, { recursive: true });
for (const [from, to] of moves) move(join(project, from), join(target, to));
const at = (dir) => (dryRun ? join(project, moves.find(([, t]) => t === dir)?.[0] ?? dir) : join(target, dir));

// Specs : build déterministe (plus de date dans .build.json)
editJson(join(at('ui'), 'site', '.build.json'), (d) => delete d.builtAt);

// Prototype : chemin des specs
editJson(join(at('prototype'), 'src', 'prototype.json'), (d) => {
  if (d.specs) d.specs = '../ui';
});
const check = join(at('prototype'), '.check');
if (existsSync(check)) {
  log('removed prototype .check/ (regenerated by check.mjs)');
  if (!dryRun) rmSync(check, { recursive: true });
}

// Cahier des charges : noms anglais, chemins, artifact
const req = at('requirements');
if (existsSync(join(req, 'cdc.json'))) {
  const config = JSON.parse(readFileSync(join(req, 'cdc.json'), 'utf8'));
  const oldOutput = config.output;
  if (config.specs) config.specs = '../ui';
  if (config.prototype) config.prototype = '../prototype';
  config.output = 'requirements.md';
  if (config.artifacts?.cdc !== undefined) {
    config.artifacts.requirements = config.artifacts.cdc;
    delete config.artifacts.cdc;
  }
  if (!dryRun) {
    writeFileSync(join(req, 'requirements.json'), JSON.stringify(config, null, 2) + '\n');
    rmSync(join(req, 'cdc.json'));
  }
  log('cdc.json → requirements.json (output, specs, prototype, artifacts.requirements)');
  if (oldOutput && oldOutput !== 'requirements.md') {
    move(join(req, oldOutput), join(req, 'requirements.md'));
    move(join(req, oldOutput.replace(/\.md$/, '.html')), join(req, 'requirements.html'));
  }
  move(join(req, 'CDC.md'), join(req, 'REQUIREMENTS.md'));
  if (existsSync(join(req, 'publish'))) {
    log('removed publish/ (regenerated by build.mjs)');
    if (!dryRun) rmSync(join(req, 'publish'), { recursive: true });
  }
}

// Paquet Design System : chemin des specs
editJson(join(at('design-system-package'), 'package.json'), (d) => {
  if (d.specsUi) d.specsUi = '../ui';
});

console.log(`\nDone. Next:
  - rebuild: build.mjs specs/ui, build.mjs specs/prototype, extract.mjs + build.mjs specs/requirements;
  - review the paths quoted in CONTEXTE.md, PROTOTYPE.md and REQUIREMENTS.md;
  - the artifacts keep their URL: publish as usual, only changed pages are sent.`);
